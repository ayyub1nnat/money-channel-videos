def circ(cx, cy, r):
    return f"M{cx+r} {cy} A{r} {r} 0 1 1 {cx+r-0.01} {cy-0.3}"

def gear(cx, cy, r, teeth=8):
    pts = []
    for i in range(teeth * 2):
        a0 = math.pi * i / teeth; rr = r if i % 2 == 0 else r * 0.78
        for a in (a0 - math.pi / teeth / 2.2, a0 + math.pi / teeth / 2.2):
            pts.append((cx + math.cos(a) * rr, cy + math.sin(a) * rr))
    return "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + " Z"

def star(cx, cy, r):
    pts = []
    for i in range(10):
        a = -math.pi / 2 + math.pi * i / 5; rr = r if i % 2 == 0 else r * 0.45
        pts.append((cx + math.cos(a) * rr, cy + math.sin(a) * rr))
    return "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + " Z"

